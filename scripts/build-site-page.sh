#!/usr/bin/env bash
# Rebuilds internal/sitepage/page.tmpl: the default page of new sites.
# Its CSS is Tailwind, compiled from src/page.src.html and inlined, so the
# page has no external requests (no CDN, no fonts) and loads instantly.
# Run after editing src/page.src.html or src/input.css; commit the result.
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
cd "$repo/internal/sitepage"
# Tailwind resolves @import "tailwindcss" next to the input file: compile a
# copy placed in web/node_modules (run "npm ci" in web/ first).
[ -d "$repo/web/node_modules/tailwindcss" ] || { echo "run npm ci in web/ first" >&2; exit 1; }
tmp="$repo/web/node_modules/.cache/sitepage-input.css"
mkdir -p "$(dirname "$tmp")"
sed "s#@source \"./page.src.html\"#@source \"$repo/internal/sitepage/src/page.src.html\"#" src/input.css > "$tmp"
css=$(cd "$repo/web" && npx --yes @tailwindcss/cli@4 -i "$tmp" --minify 2>/dev/null)
rm -f "$tmp"
python3 - "$css" <<'PY'
import sys
css = sys.argv[1].replace("</", "<\\/")
src = open("src/page.src.html").read()
assert "/*TAILWIND*/" in src
open("page.tmpl", "w").write(
    "{{/* Generated by scripts/build-site-page.sh from src/page.src.html: do not edit. */}}\n"
    + src.replace("/*TAILWIND*/", css))
PY
echo "wrote internal/sitepage/page.tmpl ($(wc -c < page.tmpl) bytes)"
